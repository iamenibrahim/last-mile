"""Emit the pitch tables as Markdown.

    python -m grounded_eval.report > grounded_eval/results/REPORT.md

Reads whatever grounded_eval/results holds and formats it. Deliberately dumb: it does
no computation of its own, so nothing can appear in the deck that the harness
did not measure. Missing inputs are reported as missing, never filled in.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

RESULTS = Path(__file__).resolve().parent / "results"


def _load(name: str) -> dict | None:
    path = RESULTS / name
    if not path.exists():
        return None
    try:
        with path.open(encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return None


def _pct(x) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def main() -> int:
    lines: list[str] = []
    w = lines.append

    w("# Last-Mile Alert - evaluation report")
    w("")
    w("Generated by `python -m grounded_eval.report`. Every figure below comes from")
    w("`eval/metrics.py` or `eval/impact.py` over real NWS products in")
    w("`data/cached_alerts`. Nothing here is estimated or carried over.")
    w("")

    metrics = _load("metrics_en.json")
    if not metrics:
        w("> **No metrics found.** Run `python -m grounded_eval.metrics --lang en --ablate` first.")
    else:
        engines = metrics["engines"]
        stub = not (metrics.get("semantic_embeddings") and metrics.get("llm_judge"))
        w("## Configuration")
        w("")
        w(f"- corpus: **{metrics['corpus_size']} alerts**, language `{metrics['lang']}`")
        w(f"- generated: {metrics['generated_at']}")
        w("- engines: " + ", ".join(f"`{k}={v}`" for k, v in engines.items()))
        if stub:
            w("")
            w("> **These numbers were produced with local stub engines.** The embedder is a")
            w("> lexical bag-of-words vectoriser and the judge is a rule-based check, not")
            w("> Azure OpenAI. They measure whether the *pipeline* catches the failures it")
            w("> is built to catch. They are not a measurement of model quality. Set the")
            w("> Azure keys and rerun to get the other number.")
        w("")

        # -- readability ---------------------------------------------------
        r = metrics["readability"]
        w("## Reading level")
        w("")
        w("| | median FK grade |")
        w("|---|---|")
        w(f"| source alert | **{r['median_source_fk']}** |")
        w(f"| rendered output | **{r['median_output_fk']}** |")
        w(f"| rendered output, excluding locked entities | **{r['median_output_fk_excluding_locked_entities']}** |")
        w("")
        w(f"- at or below grade {r['target_grade']}: **{_pct(r['pct_at_or_below_target'])}** of alerts")
        w(f"- at or below grade {r['target_grade']} excluding locked entities: "
          f"**{_pct(r['pct_at_or_below_target_excluding_locked_entities'])}**")
        w(f"- n = {r['n']} alerts long enough to score")
        w(f"- scope: {r['applies_to']}")
        w("")
        w(f"**Finding.** {r['finding']}")
        w("")
        w(f"**Floor.** {r['floor_note']}")
        w("")

        # -- entity preservation -------------------------------------------
        e = metrics["entity_preservation"]
        w("## Entity preservation")
        w("")
        w(f"- entities locked across the corpus: **{e['entities_locked']:,}**")
        w(f"- integrity failures on the clean run: **{e['integrity_failures']}**")
        w(f"- preservation rate: **{e['rate']:.4%}**")
        w("")
        w("This is a structural property, not a measured tendency: the model never")
        w("receives the entity text, so it cannot paraphrase it. `tests/test_entity_integrity.py`")
        w("is the proof; this row is the corpus-scale confirmation.")
        w("")

        # -- abstention ----------------------------------------------------
        a = metrics["abstention"]
        w("## Abstention")
        w("")
        w(f"- chosen semantic-fidelity threshold: **{a['chosen_threshold']}**")
        w(f"- abstention recall: **{_pct(a['recall'])}**")
        w(f"- false-abstention rate on clean text: **{_pct(a['false_abstention_rate'])}**")
        w(f"- tuning rule: {a['note']}")
        w("")
        w("### By corruption class")
        w("")
        w("| corruption | n | recall | caught by |")
        w("|---|---|---|---|")
        for row in a["by_class"]:
            caught = ", ".join(f"{k} ({v})" for k, v in row["caught_by"].items()) or "-"
            w(f"| `{row['class']}` | {row['n']} | {_pct(row['recall'])} | {caught} |")
        w("")
        w("> **Read this table carefully before quoting it.** Recall is measured against")
        w("> five mechanical corruption classes that this harness generates. A real")
        w("> model fails in subtler ways than a regex does. What the table supports is")
        w("> that each check catches the failure class it was designed for; it does not")
        w("> support a claim about all possible transformation failures.")
        w("")

        # -- ablation ------------------------------------------------------
        ab = metrics.get("ablation_no_entity_lock")
        if ab:
            w("### What entity locking buys")
            w("")
            w("Same corruptions, same thresholds, entity locking disabled.")
            w("")
            w("| corruption | with lock | without lock |")
            w("|---|---|---|")
            without = {row["class"]: row for row in ab["by_class"]}
            for row in a["by_class"]:
                other = without.get(row["class"], {})
                w(f"| `{row['class']}` | {_pct(row['recall'])} | {_pct(other.get('recall'))} |")
            w("")
            w("Number and road corruptions are the columns that move. Without the lock")
            w("they are caught only when a downstream check happens to notice; with it")
            w("they cannot occur undetected, because a tampered sentinel is missing by")
            w("definition.")
            w("")
        else:
            w("> Ablation not run. `python -m grounded_eval.metrics --lang en --ablate`")
            w("")

        # -- latency -------------------------------------------------------
        lat = metrics["latency_ms"]
        w("## Latency")
        w("")
        w(f"- p50: **{lat['p50']} ms**, p95: **{lat['p95']} ms**, max: {lat['max']} ms (n={lat['n']})")
        w(f"- scope: {lat['scope']}")
        w("")

        # -- instruction coverage ------------------------------------------
        ic = metrics["instruction_coverage_finding"]
        w("## Instruction coverage in the source feed")
        w("")
        w(f"- **{ic['with_instruction']} of {ic['alerts']}** cached alerts carry a non-empty")
        w(f"  `instruction` field (**{_pct(ic['pct_with_instruction'])}**)")
        w("")
        w("Alerts without one get no action list at all. The system does not infer")
        w("actions, so this is a property of the source feed, reported rather than scored.")
        w("")

        # -- translation quality -------------------------------------------
        tq = metrics["translation_quality"]
        w("## Translation quality")
        w("")
        if tq.get("applicable"):
            w(f"- {tq['metric']}: **{tq['score']}** over {tq['segments']} segments")
            w(f"- **{tq['kind']}**")
            w("")
            w("There are no reference translations for these alerts, so this is")
            w("back-translation agreement and nothing more. It is not chrF++ against a")
            w("human reference and must not be quoted as one.")
        else:
            w(f"- not applicable: {tq.get('reason')}")
        w("")

    # -- impact -------------------------------------------------------------
    impact = _load("impact.json")
    w("## Impact")
    w("")
    if not impact:
        w("> Not computed. Run `python -m grounded_eval.impact --state 51`.")
    elif not impact.get("available"):
        w("> **Unavailable.** " + str(impact.get("reason", "")).replace("\n", " "))
        w(">")
        w("> No figure is shown because no data backs one. `api.census.gov` now requires")
        w("> a key for every dataset and year, which is a change from the brief's")
        w("> assumption; signup is free and instant.")
    else:
        w(f"**{impact['headline']}**")
        w("")
        pa = impact["person_alerts"]
        w("| measure | value |")
        w("|---|---|")
        w(f"| counties covered | {impact['counties_covered']} of {impact['counties_in_state']} |")
        w(f"| LEP residents in covered counties | {impact['lep_in_covered_counties']:,} |")
        w(f"| person-alerts, county attribution (upper bound) | {pa['county_attribution']:,} |")
        w(f"| person-alerts, area weighted (central estimate) | {pa['area_weighted']:,} |")
        w(f"| statewide LEP population, for scale | {impact['lep_statewide']:,} |")
        w("")
        w("Caveats, all of which belong on the slide:")
        for c in impact["caveats"]:
            w(f"- {c}")
    w("")

    w("## What this system does not claim")
    w("")
    w("- It does not originate alerts. It only transforms authoritative ones.")
    w("- A valid manifest proves faithful transformation of a fetch we attest to.")
    w("  It does **not** prove NWS signed anything: CAP products served over")
    w("  `api.weather.gov` are not individually signed in a way this system can")
    w("  verify end to end. The trust anchor is TLS plus our own signature.")
    w("- It does not integrate with IPAWS. That needs a COG agreement.")
    w("- It does not detect deepfakes or manipulated alerts.")
    w("- Target-language readability is not measured. Flesch-Kincaid is English-only.")
    w("")

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
